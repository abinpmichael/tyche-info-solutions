<script>
$(document).ready(function () {
    $(".js").on("submit", function (e) {
        e.preventDefault();

        var form = $(this);
        var formData = form.serialize();
        var messageBox = $("#form-message");

        $.ajax({
            type: "POST",
            url: "submit-form.php",
            data: formData,
            dataType: "json",
            success: function (response) {
                if (response.success) {
                    messageBox
                        .removeClass("alert-error d-none")
                        .addClass("alert alert-success")
                        .html("Message sent successfully!")
                        .fadeIn();

                    form[0].reset();
                } else {
                    messageBox
                        .removeClass("alert-success d-none")
                        .addClass("alert alert-error")
                        .html("Something went wrong. Please try again.")
                        .fadeIn();
                }

                setTimeout(function () {
                    messageBox.fadeOut();
                }, 5000);
            },
            error: function (xhr, status, error) {
                console.error("Error:", error);
                messageBox
                    .removeClass("alert-success d-none")
                    .addClass("alert alert-error")
                    .html("An error occurred. Please try again.")
                    .fadeIn();

                setTimeout(function () {
                    messageBox.fadeOut();
                }, 5000);
            }
        });
    });
});
